#!/usr/bin/env python3
"""Write hdl/core/panel_labels.svh: a 4-character screen label for each of
the original panel's 128 buttons (physical button number = 16 x panel word
+ bit), abbreviated from sim/devices/synth.py ORK_BUTTONS (NED's logical
names, 05-BUTT:075-OLDL).

Run:  python3 tools/gen_panel_labels.py
tests/hdl/test_board.py checks that the file is up to date and reads the
labels back from the screen.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from sim.devices.synth import ORK_BUTTONS  # noqa: E402

PATH = os.path.join(ROOT, "hdl", "core", "panel_labels.svh")

FIXED = {
    "ve.del": "VDel", "ve.atk": "VAtk", "ve.idec": "VIDc", "ve.fdec": "VFDc",
    "ve.peak": "VPk", "ve.sust": "VSus",
    "he.del": "HDel", "he.atk": "HAtk", "he.idec": "HIDc", "he.fdec": "HFDc",
    "he.peak": "HPk", "he.sust": "HSus",
    "hgs1": "HGS1", "hgs2": "HGS2", "scale.a": "Scal", "ttben": "TTbn",
    "start": "Strt", "stop": "Stop", "record": "Rec", "punch": "Pnch",
    "cont": "Cont", "rew": "Rew", "ff": "FF", "erase": "Ers", "eloop": "ELp",
    "transp": "Trns", "speed": "Spd", "bounce": "Bnc", "smt": "SMT", "skt": "SKT",
    "click": "Clik", "ext": "Ext",
    "ptun": "PTun", "vwave": "ViWv", "vrate": "ViRt", "vdepth": "ViDp", "vatk": "ViAt",
    "ponoff": "Port", "plogl": "PLog", "prate": "PRt", "ratio": "Rat", "decay": "Dcy",
    "repeat": "Rpt", "arpeg": "Arp", "rrate": "RRt", "chorus": "Chor", "tbase": "TBas",
    "oratio": "ORat",
    "vkvel": "Vel", "vkpre": "Pres", "vkpe1": "PE1", "vkpe2": "PE2", "vkmod": "Mod",
    "vkrib": "Rib", "vkkcv": "KCV", "vkbth": "Bth", "smpte": "SMPT", "smin": "SMIn",
    "scon": "SCon", "midi": "MIDI", "vkper": "VPer", "vkrec": "VRec", "vkove": "VOvr",
    "vkclr": "VClr",
    "bnkovwrt": "BkOW", "entrywrt": "EnWr", "lpt": "LPT", "lpfc": "LPFc", "hpt": "HPT",
    "hpfc": "HPFc", "bpt": "BPT", "bpfc": "BPFc", "bwdth": "BW", "dsel": "DSel",
}
PREFIX = {"psel": "PS", "coef": "C", "trak": "Tr", "bank": "Bk", "timb": "Tb", "seqr": "Sq"}


def labels():
    """128 labels, 4 characters each (space padded)."""
    out = []
    for name in ORK_BUTTONS:
        if name in FIXED:
            lab = FIXED[name]
        else:
            stem, n = name.split(".")
            lab = PREFIX[stem] + str(int(n) + 1)          # numbered from 1, as printed
        assert len(lab) <= 4, name
        out.append(lab.ljust(4))
    assert len(out) == 128 and len(set(out)) == 128
    return out


def text():
    lines = ["// Generated by tools/gen_panel_labels.py from sim/devices/synth.py",
             "// ORK_BUTTONS. Do not edit. {button number[6:0], character[1:0]}.",
             "function automatic logic [7:0] panel_label(input logic [8:0] a);",
             "    case (a)"]
    for b, lab in enumerate(labels()):
        for k, ch in enumerate(lab):
            if ch != " ":
                lines.append("        9'd%d: panel_label = 8'h%02x;   // %s" % (b * 4 + k, ord(ch), lab.strip()))
    lines += ["        default: panel_label = 8'h20;", "    endcase", "endfunction", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    with open(PATH, "w") as f:
        f.write(text())
    print("wrote", PATH)
