#!/usr/bin/env python3
"""Write hdl/core/midi_tables.svh: the MIDI arithmetic of midi_in.sv and
midi_vpk.sv as 128-entry tables (7-bit inputs), so it costs a few LUT levels
instead of a divider chain (timing at 50 MHz). The functions here are the
definitions; the HDL only looks them up.

  ork_key(n)   midi_in: note n folded by octaves into MIDI 36..96, then
               k = n - 36 as {octave k / 12 [6:4], bit k % 12 [3:0]}
  vpk_key(n)   midi_vpk: note n folded into MIDI 33..108, minus 33
  scale180(v), scale225(v)   midi_vpk: round(v x span / 127)
               = (v x span + 63) // 127

Run:  python3 tools/gen_midi_tables.py   (tests/hdl/test_board.py checks it)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, "hdl", "core", "midi_tables.svh")


def ork_key(n):
    if n < 36:
        n += 12 * ((47 - n) // 12)
    if n > 96:
        n -= 12 * ((n - 85) // 12)
    k = n - 36
    return (k // 12) << 4 | (k % 12)


def vpk_key(n):
    if n < 33:
        n += 12 * ((44 - n) // 12)
    if n > 108:
        n -= 12 * ((n - 97) // 12)
    return n - 33


def scale(v, span):
    return (v * span + 63) // 127


def table(name, width, f):
    lines = ["function automatic logic [%d:0] %s(input logic [6:0] n);" % (width - 1, name),
             "    case (n)"]
    for n in range(128):
        lines.append("        7'd%d: %s = %d'd%d;" % (n, name, width, f(n)))
    lines += ["        default: %s = '0;" % name, "    endcase", "endfunction", ""]
    return lines


def text():
    lines = ["// Generated by tools/gen_midi_tables.py (the definitions are there). Do not edit."]
    lines += table("ork_key", 7, ork_key)
    lines += table("vpk_key", 7, vpk_key)
    lines += table("scale180", 8, lambda v: scale(v, 180))
    lines += table("scale225", 8, lambda v: scale(v, 225))
    return "\n".join(lines)


if __name__ == "__main__":
    with open(PATH, "w") as f:
        f.write(text())
    print("wrote", PATH)
