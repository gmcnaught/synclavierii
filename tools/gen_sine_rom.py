#!/usr/bin/env python3
"""Write hdl/dev/sine_rom.svh from sim/voice.py SINE_ROM (the modulator
waveform, a CHOICE until the SS2 ROMs are dumped).

Run:  python3 tools/gen_sine_rom.py
tests/hdl/test_lockstep.py checks that the file matches SINE_ROM.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from sim.voice import SINE_ROM  # noqa: E402

PATH = os.path.join(ROOT, "hdl", "dev", "sine_rom.svh")


def text():
    lines = ["// Generated by tools/gen_sine_rom.py from sim/voice.py SINE_ROM. Do not edit.",
             "// round(127.5 + 127.5 sin(2 pi n / 256)), clipped to 0-255 [CHOICE].",
             "function automatic logic [7:0] sine_rom(input logic [7:0] n);",
             "    case (n)"]
    for n in range(256):
        lines.append("        8'd%d: sine_rom = 8'd%d;" % (n, SINE_ROM[n]))
    lines += ["        default: sine_rom = 8'd0;", "    endcase", "endfunction", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    with open(PATH, "w") as f:
        f.write(text())
    print("wrote", PATH)
