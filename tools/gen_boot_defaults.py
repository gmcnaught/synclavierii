#!/usr/bin/env python3
"""Write hdl/core/boot_defaults.svh: the state of a freshly built Python
system (sim/system.py make_system(floppy=True, synth=True)), as writes to
able_system's load ports.

On the board nothing loads state from a trace; hdl/core/boot_loader.sv
replays these writes while the CPU is held in reset, so the HDL starts
exactly where the Python simulator starts (then clears the memories and
loads MONITOR). The entries are the 'V' (device), 'O' (voice engine) and
register sections sim/lockstep.py writes for the same system. Wave memory
and the memories are cleared separately (they are zero in Python).

Run:  python3 tools/gen_boot_defaults.py
tests/hdl/test_board.py checks that the file is up to date.
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

PATH = os.path.join(ROOT, "hdl", "core", "boot_defaults.svh")

DEV, VOICE, DBG = 0, 1, 2


def entries():
    """(kind, sel, addr, data) for a fresh system, in load order."""
    from sim.lockstep import _Audio, _device_header, _flags
    from sim.system import make_system
    cpu = make_system(floppy=True, synth=True)
    out = []
    h = _device_header(cpu)
    p = 0
    while p < len(h):
        k = h[p:p + 1]
        p += 1
        if k == b"X":
            sectors, = struct.unpack_from("<I", h, p)
            p += 4 + sectors * 512
        elif k == b"V":
            sel, addr, v = struct.unpack_from("<BHI", h, p)
            p += 7
            if sel != 6:                    # wave memory: cleared as a whole
                out.append((DEV, sel, addr, v))
        else:
            raise ValueError("unexpected header section %r" % k)
    o = _Audio(cpu.fm).header()
    rr, to_next, phase = struct.unpack_from("<QHB", o, 1)
    out.append((VOICE, 0, 32, rr))
    out.append((VOICE, 0, 33, phase << 14 | to_next))
    for c in range(16):
        acc, pre, point = struct.unpack_from("<HBB", o, 12 + 4 * c)
        out.append((VOICE, 0, c, acc << 15 | pre << 8 | point))
    for i, r in enumerate(cpu.r):
        out.append((DBG, 0, i, r))
    out.append((DBG, 0, 16, _flags(cpu)))
    # Model C/D state (able_cpu.sv debug addresses 17-23): page, link,
    # repeat counters, repeat word/pc, D2, interrupt shadow
    for i, v in enumerate((cpu.page, cpu.ppc, cpu.rpt_next << 8 | cpu.rpt_left, cpu.rpt_word,
                           cpu.rpt_pc, cpu.d2, cpu.int_shadow)):
        out.append((DBG, 0, 17 + i, int(v)))
    return out


def text():
    es = entries()
    lines = ["// Generated by tools/gen_boot_defaults.py from a fresh sim/system.py",
             "// system (make_system(floppy=True, synth=True)). Do not edit.",
             "// Entry: {kind[1:0] (0 ld_dev, 1 ld_voice, 2 dbg), sel[2:0], addr[12:0], data[63:0]}",
             "localparam int BOOT_DEFAULTS = %d;" % len(es),
             "function automatic logic [81:0] boot_default(input logic [8:0] i);",
             "    case (i)"]
    for i, (kind, sel, addr, data) in enumerate(es):
        lines.append("        9'd%d: boot_default = {2'd%d, 3'd%d, 13'd%d, 64'd%d};"
                     % (i, kind, sel, addr, data))
    lines += ["        default: boot_default = '0;", "    endcase", "endfunction", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    with open(PATH, "w") as f:
        f.write(text())
    print("wrote", PATH, len(entries()), "entries")
