#!/usr/bin/env python3
"""Generate the FM voice pan law used by sim/voice.py and hdl/dev/dev_fm.sv.

Equal power: for the 6-bit stereo position p (ISHC bits 7-2; pan = 4p,
0 = all left, 32 = centre), theta = (pi / 2) x pan / 256 and
  left = round(256 cos theta), right = round(256 sin theta)
so a hard-panned voice has the full factor (256) on its side and a centred
one 181 (-3 dB) on each. The voice cards do this with a 256 x 8 pan PROM
that has not been dumped; Arturia Synclavier V (by NED's programmer) is
equal-power (docs/tuning-references.md). Before M23 the core was linear
(left = 256 - pan, right = pan).

  python3 tools/gen_pan_law.py           # write sim/pan_law.py and hdl/dev/pan_law.svh
  python3 tools/gen_pan_law.py --check   # exit 1 if they differ from a fresh build
"""
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def table():
    left, right = [], []
    for p in range(64):
        theta = math.pi / 2 * (4 * p) / 256
        left.append(round(256 * math.cos(theta)))
        right.append(round(256 * math.sin(theta)))
    return left, right


def py_text(left, right):
    def rows(v):
        return ",\n".join("    " + ", ".join(str(x) for x in v[i:i + 16]) for i in range(0, 64, 16))
    return ('"""Generated by tools/gen_pan_law.py: do not edit.\n\n'
            'FM voice pan law (equal power), indexed by ISHC bits 7-2 (pan >> 2):\n'
            'left and right factors, full = 256."""\n\n'
            f"PAN_L = (\n{rows(left)},\n)\nPAN_R = (\n{rows(right)},\n)\n")


def sv_text(left, right):
    lines = ["// Generated by tools/gen_pan_law.py: do not edit.",
             "// FM voice pan law (equal power; sim/pan_law.py), indexed by ISHC bits 7-2:",
             "// {left, right} factors, full = 256.",
             "function automatic logic [17:0] pan_law(input logic [5:0] p);",
             "    case (p)"]
    for p in range(64):
        lines.append(f"        6'd{p}: pan_law = {{9'd{left[p]}, 9'd{right[p]}}};")
    lines += ["        default: pan_law = '0;", "    endcase", "endfunction", ""]
    return "\n".join(lines)


def main(argv):
    left, right = table()
    outs = {ROOT / "sim" / "pan_law.py": py_text(left, right),
            ROOT / "hdl" / "dev" / "pan_law.svh": sv_text(left, right)}
    if "--check" in argv:
        bad = [str(p) for p, t in outs.items() if not p.exists() or p.read_text() != t]
        if bad:
            print("out of date:", ", ".join(bad))
            return 1
        return 0
    for p, t in outs.items():
        p.write_text(t)
    print("centre", left[32], right[32], "hard left", left[0], right[0], "p=63", left[63], right[63])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
