// D24-D27 SCSI host adaptor and one disk target (sim/devices/scsi.py; the
// evidence and the model are described there).
//   D24 write: with bit 10000 select a D24 board (only board 0, bit 400,
//              exists), else the initiator's data bits 7-0. Read: select
//              bits | the initiator's data bits | the byte the target
//              drives in data-in or status phase.
//   D25 write: the initiator's signals (ATN 1, BSY 2, ACK 4, RST 10, SEL
//              40, ...): RST frees the bus; with the bus free, SEL with BSY
//              released and the target's bit on the data bus selects it;
//              ACK raised by hand while REQ is up moves one byte. Read: the
//              initiator's signals | the target's (BSY, MSG, C/D, I/O, REQ;
//              no REQ while ACK is held).
//   D26 / D27: one byte / two bytes (first in bits 15-8) with the
//              handshake done for the CPU.
// Bus phases and commands exactly as the Python model (TEST UNIT READY,
// REZERO, REQUEST SENSE, READ(6/10), WRITE(6/10), SEEK, INQUIRY, MODE
// SELECT, RESERVE, RELEASE, MODE SENSE, START/STOP, PREVENT/ALLOW, READ
// CAPACITY, VERIFY; others CHECK CONDITION, ILLEGAL REQUEST).
// The disk is 512-byte blocks of 256 big-endian words behind a word port
// (sd_floppy drive 3); a byte the CPU needs from it is fetched while the
// access waits for its ack, which costs no simulated time.
module dev_scsi #(
    parameter logic [3:0] TARGET = 4'd5          // the disk's SCSI ID
) (
    input  logic        clk,
    input  logic        rst,
    input  logic        sel,
    input  logic        rd,
    input  logic        wr,
    input  logic [1:0]  reg_sel,      // 0 D24, 1 D25, 2 D26, 3 D27
    input  logic [15:0] wdata,
    output logic [15:0] rdata,
    output logic        ack,

    input  logic        present,
    input  logic        protect,
    input  logic [16:0] blocks,
    output logic [23:0] d_addr,       // {block[15:0], word[7:0]}
    output logic        d_rd,
    output logic        d_wr,
    output logic [15:0] d_wdata,
    input  logic [15:0] d_rdata,
    input  logic        d_ack
);
    localparam logic [8:0] ATN = 9'o1, BSY = 9'o2, ACK = 9'o4, RST = 9'o10, MSG = 9'o20,
                           SEL = 9'o40, CD = 9'o100, REQ = 9'o200, IO = 9'o400;
    typedef enum logic [2:0] {P_FREE, P_MSG_OUT, P_COMMAND, P_DATA_IN, P_DATA_OUT, P_STATUS,
                              P_MSG_IN} phase_t;
    phase_t phase;

    function automatic logic [8:0] phase_sig(input phase_t p);
        case (p)
            P_MSG_OUT:  phase_sig = BSY | MSG | CD | REQ;
            P_COMMAND:  phase_sig = BSY | CD | REQ;
            P_DATA_IN:  phase_sig = BSY | IO | REQ;
            P_DATA_OUT: phase_sig = BSY | REQ;
            P_STATUS:   phase_sig = BSY | CD | IO | REQ;
            P_MSG_IN:   phase_sig = BSY | MSG | CD | IO | REQ;
            default:    phase_sig = 9'd0;
        endcase
    endfunction

    logic [15:0] select_bits;
    logic [7:0]  data_out;
    logic [8:0]  sig_out;
    logic        acked;
    logic [7:0]  cdb [12];
    logic [3:0]  cdb_n;
    logic [7:0]  status, sense_key, last_sense;

    // data phase: from the disk or generated (INQUIRY etc.); to the disk or discarded
    typedef enum logic [2:0] {G_DISK, G_INQ, G_CAP, G_MODE, G_SENSE} gen_t;
    gen_t        src;
    logic [24:0] len, pos;
    logic [16:0] lba;
    logic        out_disk;
    logic [7:0]  wbuf;

    // the word of the stream the CPU is at (disk data)
    logic        cw_ok;
    logic [23:0] cw_word;            // stream word index
    logic [15:0] cw;
    wire  [23:0] want_word = pos[24:1];
    wire  [16:0] want_blk  = lba + {1'b0, want_word[23:8]};

    // generated bytes
    function automatic logic [7:0] gen_byte(input gen_t g, input logic [24:0] i,
                                            input logic [16:0] nblk, input logic [7:0] sk);
        logic [31:0] last;
        gen_byte = 8'd0;
        last = {15'd0, nblk} - 32'd1;
        case (g)
            G_INQ: begin
                logic [8*36-1:0] inq;
                inq = {8'd0, 8'd0, 8'd1, 8'd1, 8'd31, 8'd0, 8'd0, 8'd0,
                       "MiSTer  ", "SYNCLAVIER W0   ", "1.0 "};
                if (i < 25'd36) gen_byte = inq[8*(35 - i[5:0]) +: 8];
            end
            G_CAP: case (i[2:0])
                3'd0: gen_byte = last[31:24];
                3'd1: gen_byte = last[23:16];
                3'd2: gen_byte = last[15:8];
                3'd3: gen_byte = last[7:0];
                3'd6: gen_byte = 8'h02;                      // 512
                default: gen_byte = 8'd0;
            endcase
            G_MODE: case (i[3:0])
                4'd0: gen_byte = 8'd11;
                4'd3: gen_byte = 8'd8;
                4'd5: gen_byte = {7'd0, nblk[16]};
                4'd6: gen_byte = nblk[15:8];
                4'd7: gen_byte = nblk[7:0];
                4'd10: gen_byte = 8'h02;
                default: gen_byte = 8'd0;
            endcase
            G_SENSE: case (i[4:0])
                5'd0: gen_byte = 8'h70;
                5'd2: gen_byte = sk;
                5'd7: gen_byte = 8'd10;
                default: gen_byte = 8'd0;
            endcase
            default: ;
        endcase
    endfunction

    wire [7:0] stream_byte = src == G_DISK ? (pos[0] ? cw[7:0] : cw[15:8])
                                           : gen_byte(src, pos, blocks, last_sense);
    wire need_fetch = phase == P_DATA_IN && src == G_DISK && !(cw_ok && cw_word == want_word);
    wire [7:0] peek = phase == P_DATA_IN ? stream_byte : (phase == P_STATUS ? status : 8'd0);

    // --------------------------------------------------------- sequencer
    typedef enum logic [2:0] {Q_IDLE, Q_FETCH, Q_RUN, Q_STORE, Q_EXEC, Q_ACK} q_t;
    q_t          q;
    logic [1:0]  nbytes;              // bytes still to move for this access
    logic        is_get, is_peek;
    logic [15:0] put_word;
    logic [15:0] acc;                 // bytes got so far

    wire [3:0] cdb_need = cdb[0][7:5] == 3'd0 ? 4'd6 : (cdb[0][7:5] <= 3'd2 ? 4'd10 : 4'd12);
    wire start = sel && (rd || wr) && !ack && q == Q_IDLE;

    logic [23:0] st_addr;            // the word being written
    assign d_addr  = q == Q_STORE ? st_addr : {want_blk[15:0], want_word[7:0]};
    assign d_rd    = q == Q_FETCH;
    assign d_wr    = q == Q_STORE;
    assign d_wdata = {wbuf, put_word[7:0]};

    always_ff @(posedge clk) begin
        ack <= 1'b0;
        if (rst) begin
            q <= Q_IDLE;
            phase <= P_FREE;
            select_bits <= '0; data_out <= '0; sig_out <= '0; acked <= 1'b0;
            cdb_n <= '0; status <= '0; sense_key <= '0; last_sense <= '0;
            cw_ok <= 1'b0; len <= '0; pos <= '0;
        end else case (q)
        Q_IDLE: if (start) begin
            case (reg_sel)
            2'd0: if (wr) begin
                if (wdata[12]) select_bits <= wdata & 16'o400;
                else data_out <= wdata[7:0];
                q <= Q_ACK;
            end else begin
                is_peek <= 1'b1; nbytes <= 2'd0;
                q <= need_fetch ? Q_FETCH : Q_RUN;
            end
            2'd1: if (rd) begin
                rdata <= {7'd0, sig_out | (phase_sig(phase) & (acked ? ~REQ : 9'h1FF))};
                q <= Q_ACK;
            end else begin
                sig_out <= wdata[8:0];
                if (!wdata[2]) acked <= 1'b0;
                if (wdata[3]) begin                                   // RST
                    phase <= P_FREE; cdb_n <= '0;
                    q <= Q_ACK;
                end else if (phase == P_FREE) begin                   // selection
                    if (present && wdata[5] && !wdata[1] && data_out[TARGET[2:0]]) begin
                        phase <= wdata[0] ? P_MSG_OUT : P_COMMAND;
                        cdb_n <= '0;
                    end
                    q <= Q_ACK;
                end else if (wdata[2] && !sig_out[2] && !acked) begin // ACK by hand
                    acked <= 1'b1;
                    is_peek <= 1'b0; nbytes <= 2'd1; acc <= '0;
                    if (phase == P_DATA_IN || phase == P_STATUS || phase == P_MSG_IN) begin
                        is_get <= 1'b1;
                        q <= need_fetch ? Q_FETCH : Q_RUN;
                    end else begin
                        is_get <= 1'b0; put_word <= {8'd0, data_out};
                        q <= Q_RUN;
                    end
                end else q <= Q_ACK;
            end
            default: begin                                            // D26, D27
                is_peek <= 1'b0; acc <= '0;
                nbytes <= reg_sel[0] ? 2'd2 : 2'd1;
                is_get <= rd;
                put_word <= reg_sel[0] ? wdata : {8'd0, wdata[7:0]};
                q <= (rd && need_fetch) ? Q_FETCH : Q_RUN;
            end
            endcase
        end

        Q_FETCH: if (d_ack) begin
            cw <= d_rdata; cw_word <= want_word; cw_ok <= 1'b1;
            q <= Q_RUN;
        end

        Q_RUN: begin
            if (is_peek) begin
                rdata <= select_bits | {8'd0, data_out} | {8'd0, peek};
                q <= Q_ACK;
            end else if (nbytes == 2'd0) begin
                if (is_get) rdata <= reg_sel == 2'd3 ? acc : {8'd0, acc[7:0]};
                q <= Q_ACK;
            end else if (is_get) begin                                // take one byte
                logic [7:0] b;
                b = 8'o377;
                case (phase)
                    P_DATA_IN: begin
                        b = stream_byte;
                        pos <= pos + 25'd1;
                        if (pos + 25'd1 == len) phase <= P_STATUS;
                    end
                    P_STATUS: begin b = status; phase <= P_MSG_IN; end
                    P_MSG_IN: begin b = 8'd0; phase <= P_FREE; cdb_n <= '0; end
                    default: ;
                endcase
                acc <= {acc[7:0], b};
                nbytes <= nbytes - 2'd1;
                // the next byte may need the next disk word
                if (nbytes == 2'd2 && phase == P_DATA_IN && src == G_DISK && pos[0] &&
                    pos + 25'd1 != len)
                    q <= Q_FETCH;
            end else begin                                            // give one byte
                logic [7:0] b;
                b = nbytes == 2'd2 ? put_word[15:8] : put_word[7:0];
                nbytes <= nbytes - 2'd1;
                case (phase)
                    P_MSG_OUT:
                        if (b[7]) phase <= P_COMMAND;
                        else if (b == 8'h06 || b == 8'h0C) begin phase <= P_FREE; cdb_n <= '0; end
                    P_COMMAND: begin
                        cdb[cdb_n] <= b;
                        cdb_n <= cdb_n + 4'd1;
                        if (cdb_n + 4'd1 == ((cdb_n == 4'd0) ? (b[7:5] == 3'd0 ? 4'd6 :
                                (b[7:5] <= 3'd2 ? 4'd10 : 4'd12)) : cdb_need))
                            q <= Q_EXEC;
                    end
                    P_DATA_OUT: begin
                        pos <= pos + 25'd1;
                        if (!pos[0]) wbuf <= b;
                        else if (out_disk) begin
                            put_word <= {8'd0, b};
                            st_addr <= {want_blk[15:0], want_word[7:0]};
                            q <= Q_STORE;
                        end
                        if (pos + 25'd1 == len) begin status <= 8'h00; phase <= P_STATUS; end
                    end
                    default: ;
                endcase
            end
        end

        Q_STORE: if (d_ack) begin            // a word written (pos already advanced)
            cw_ok <= 1'b0;
            q <= Q_RUN;
        end

        Q_EXEC: begin                        // the command is complete: run it
            logic [7:0]  op;
            logic [31:0] l;
            logic [16:0] n;
            op = cdb[0];
            last_sense <= sense_key;
            sense_key <= 8'd0;
            status <= 8'h00;
            cw_ok <= 1'b0;
            pos <= '0;
            out_disk <= 1'b0;
            phase <= P_STATUS;
            case (op)
            8'h00, 8'h01, 8'h0B, 8'h16, 8'h17, 8'h1B, 8'h1E, 8'h2F: ;
            8'h03: begin src <= G_SENSE; len <= cdb[4] == 0 ? 25'd4 : (cdb[4] > 8'd18 ? 25'd18 : {17'd0, cdb[4]});
                         phase <= P_DATA_IN; end
            8'h12: if (cdb[4] != 0) begin src <= G_INQ; len <= cdb[4] > 8'd36 ? 25'd36 : {17'd0, cdb[4]};
                         phase <= P_DATA_IN; end
            8'h25: begin src <= G_CAP; len <= 25'd8; phase <= P_DATA_IN; end
            8'h1A: if (cdb[4] != 0) begin src <= G_MODE; len <= cdb[4] > 8'd12 ? 25'd12 : {17'd0, cdb[4]};
                         phase <= P_DATA_IN; end
            8'h15: if (cdb[4] != 0) begin len <= {17'd0, cdb[4]}; phase <= P_DATA_OUT; end
            8'h08, 8'h0A, 8'h28, 8'h2A: begin
                if (op[5]) begin
                    l = {cdb[2], cdb[3], cdb[4], cdb[5]};
                    n = {1'b0, cdb[7], cdb[8]};
                end else begin
                    l = {11'd0, cdb[1][4:0], cdb[2], cdb[3]};
                    n = cdb[4] == 0 ? 17'd256 : {9'd0, cdb[4]};
                end
                if (l + {15'd0, n} > {15'd0, blocks}) begin
                    status <= 8'h02; sense_key <= 8'h05;
                end else if (op[1] && protect) begin                  // write, read only
                    status <= 8'h02; sense_key <= 8'h07;
                end else if (n != 0) begin
                    lba <= l[16:0];
                    len <= {n[15:0], 9'd0};
                    src <= G_DISK;
                    out_disk <= 1'b1;
                    phase <= op[1] ? P_DATA_OUT : P_DATA_IN;
                end
            end
            default: begin status <= 8'h02; sense_key <= 8'h05; end
            endcase
            q <= nbytes == 2'd0 ? Q_RUN : Q_RUN;       // finish the access (D27: second byte done)
        end

        Q_ACK: begin
            ack <= 1'b1;
            q <= Q_IDLE;
        end
        default: q <= Q_IDLE;
        endcase
    end
endmodule
