#!/usr/bin/env python3
"""Write hdl/dev/fm_num_rom.svh: OSC_NUM x d for d = 0..1023, the
oscillator-tick numerator of an offset of d ns inside a CPU tick (sim/voice.py
OSC_CLOCK = 656015360 / 123 GHz; dev_fm.sv looks it up instead of
multiplying in the tick's clock, for timing).

Run:  python3 tools/gen_fm_tables.py   (tests/hdl/test_board.py checks it)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, "hdl", "dev", "fm_num_rom.svh")
OSC_NUM = 656015360


def text():
    lines = ["// Generated by tools/gen_fm_tables.py. Do not edit.",
             "// OSC_NUM x d (OSC_NUM = 656015360).",
             "function automatic logic [39:0] osc_num_x(input logic [9:0] d);",
             "    case (d)"]
    for d in range(1024):
        lines.append("        10'd%d: osc_num_x = 40'd%d;" % (d, OSC_NUM * d))
    lines += ["        default: osc_num_x = 40'd0;", "    endcase", "endfunction", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    with open(PATH, "w") as f:
        f.write(text())
    print("wrote", PATH)
