#!/usr/bin/env python3
"""Generate the FM output decimation filter (768 kHz -> 48 kHz) used by
sim/pcm.py and hdl/dev/pcm_out.sv.

Kaiser-windowed sinc, TAPS taps, cutoff CUTOFF_HZ at the 768 kHz input
rate, quantized to integers that sum to exactly 2**SUM_BITS (unity DC
gain). Writes sim/pcm_fir.py and hdl/dev/pcm_fir.svh; the committed files
are the reference, so the sim and the HDL use the same integers.

  python3 tools/gen_pcm_fir.py           # write both files
  python3 tools/gen_pcm_fir.py --check   # exit 1 if they differ from a fresh build
"""
import math
import pathlib
import sys

IN_RATE = 768_000
TAPS = 512
CUTOFF_HZ = 21_000
BETA = 9.0
SUM_BITS = 20
ROOT = pathlib.Path(__file__).resolve().parent.parent


def bessel_i0(x):
    s, term, k = 1.0, 1.0, 1
    while term > 1e-17 * s:
        term *= (x / (2 * k)) ** 2
        s += term
        k += 1
    return s


def design():
    fc = CUTOFF_HZ / IN_RATE
    mid = (TAPS - 1) / 2
    h = []
    for n in range(TAPS):
        m = n - mid
        sinc = 1.0 if m == 0 else math.sin(2 * math.pi * fc * m) / (2 * math.pi * fc * m)
        w = bessel_i0(BETA * math.sqrt(1 - (m / mid) ** 2)) / bessel_i0(BETA)
        h.append(2 * fc * sinc * w)
    total = sum(h)
    q = [round(x / total * (1 << SUM_BITS)) for x in h]
    # make the sum exact, keeping symmetry: adjust the two centre taps
    err = (1 << SUM_BITS) - sum(q)
    c = TAPS // 2
    q[c - 1] += err // 2
    q[c] += err - err // 2
    if err % 2:                      # odd remainder: keep symmetric, put it on the ends' neighbours
        raise ValueError("odd sum error; change SUM_BITS or the rounding")
    assert sum(q) == 1 << SUM_BITS and q == q[::-1]
    return q


def response_db(q, f):
    re = sum(c * math.cos(2 * math.pi * f / IN_RATE * n) for n, c in enumerate(q))
    im = sum(c * math.sin(2 * math.pi * f / IN_RATE * n) for n, c in enumerate(q))
    return 20 * math.log10(max(math.hypot(re, im), 1e-12) / (1 << SUM_BITS))


def py_text(q):
    rows = ",\n".join("    " + ", ".join(str(x) for x in q[i:i + 12]) for i in range(0, TAPS, 12))
    return (f'"""Generated by tools/gen_pcm_fir.py: do not edit.\n\n'
            f'FM output decimation filter, {IN_RATE} Hz -> 48 kHz: {TAPS} taps, Kaiser beta {BETA},\n'
            f'cutoff {CUTOFF_HZ} Hz; integers summing to 2**{SUM_BITS}."""\n\n'
            f"TAPS = {TAPS}\nSUM_BITS = {SUM_BITS}\nCOEFFS = (\n{rows},\n)\n")


def sv_text(q):
    width = max(abs(x) for x in q).bit_length() + 1
    lines = [f"// Generated by tools/gen_pcm_fir.py: do not edit.",
             f"// FM output decimation filter, {IN_RATE} Hz -> 48 kHz: {TAPS} taps, Kaiser beta {BETA},",
             f"// cutoff {CUTOFF_HZ} Hz; integers summing to 2**{SUM_BITS} (sim/pcm_fir.py).",
             f"localparam int FIR_TAPS = {TAPS};",
             f"localparam int FIR_SUM_BITS = {SUM_BITS};",
             f"localparam int FIR_W = {width};",
             f"function automatic logic signed [FIR_W-1:0] fir_coeff(input logic [{(TAPS - 1).bit_length() - 1}:0] i);",
             "    case (i)"]
    for i, x in enumerate(q):
        lines.append(f"        {i}: fir_coeff = {'-' if x < 0 else ''}{width}'sd{abs(x)};")
    lines += [f"        default: fir_coeff = '0;", "    endcase", "endfunction", ""]
    return "\n".join(lines)


def main(argv):
    q = design()
    outs = {ROOT / "sim" / "pcm_fir.py": py_text(q), ROOT / "hdl" / "dev" / "pcm_fir.svh": sv_text(q)}
    if "--check" in argv:
        bad = [str(p) for p, t in outs.items() if not p.exists() or p.read_text() != t]
        if bad:
            print("out of date:", ", ".join(bad))
            return 1
        return 0
    for p, t in outs.items():
        p.write_text(t)
    print(f"{TAPS} taps, max |coeff| {max(abs(x) for x in q)}, sum 2**{SUM_BITS}")
    for f in (1000, 10000, 15000, 18000, 20000, 21000, 24000, 26000, 30000, 48000, 100000):
        print(f"  {f:6d} Hz {response_db(q, f):8.2f} dB")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
